/**
 * 主题：Android 12+ 跟随系统壁纸取色；无法取色的系统回退到完整的
 * 自定义亮/暗品牌配色（见 Color.kt），保证任何设备上观感一致可用。
 */
@Composable
fun VivoiconsTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            // 提亮 surface 层级，保持系统取色主色的同时更明快活泼
            val base = if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
            base.copy(
                background = if (darkTheme) base.surfaceDim else base.surfaceBright,
                surface = if (darkTheme) base.surfaceDim else base.surfaceBright,
            )
        }
        darkTheme -> FallbackDarkScheme
        else -> FallbackLightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        shapes = AppShapes,
        typography = Typography,
        content = content,
    )
}
